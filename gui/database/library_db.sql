-- МАҢЫЗДЫ: алдымен «library_db» деректер қорын жасаңыз
-- (database/01_create_database.sql), содан кейін дәл «library_db»-ге қосылыңыз.
-- Бұл скриптті бірнеше рет орындауға болады: қолда бар деректер жойылмайды.

CREATE TABLE IF NOT EXISTS authors (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    country VARCHAR(80) NOT NULL
);

CREATE TABLE IF NOT EXISTS readers (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    full_name VARCHAR(120) NOT NULL,
    phone VARCHAR(30) NOT NULL UNIQUE
);

CREATE TABLE IF NOT EXISTS books (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    title VARCHAR(180) NOT NULL,
    author_id INTEGER NOT NULL,
    publication_year INTEGER NOT NULL,
    isbn VARCHAR(20) NOT NULL UNIQUE,
    total_copies INTEGER NOT NULL DEFAULT 1,
    available_copies INTEGER NOT NULL DEFAULT 1,
    CONSTRAINT fk_books_authors FOREIGN KEY (author_id)
        REFERENCES authors(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_books_year CHECK (publication_year BETWEEN 1450 AND 2100),
    CONSTRAINT chk_books_total CHECK (total_copies >= 1),
    CONSTRAINT chk_books_available CHECK
        (available_copies >= 0 AND available_copies <= total_copies)
);

CREATE TABLE IF NOT EXISTS loans (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    book_id INTEGER NOT NULL,
    reader_id INTEGER NOT NULL,
    loan_date DATE NOT NULL,
    due_date DATE NOT NULL,
    return_date DATE,
    CONSTRAINT fk_loans_books FOREIGN KEY (book_id)
        REFERENCES books(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT fk_loans_readers FOREIGN KEY (reader_id)
        REFERENCES readers(id) ON DELETE RESTRICT ON UPDATE CASCADE,
    CONSTRAINT chk_loans_due CHECK (due_date >= loan_date),
    CONSTRAINT chk_loans_return CHECK
        (return_date IS NULL OR return_date >= loan_date)
);

-- PostgreSQL-де MySQL-дағыдай кесте ішінде INDEX синтаксисі қолданылмайды.
CREATE INDEX IF NOT EXISTS idx_loans_reader ON loans (reader_id);
CREATE INDEX IF NOT EXISTS idx_loans_book ON loans (book_id);

